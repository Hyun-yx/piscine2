#include <stdio.h>

char	*ft_strlowcase(char *str)
{
	int	i;

	i = 0;
	while (str[i] != '\0')
	{
		if (!((str[i] >= 'a' && str[i] <= 'z')
				|| (str[i] >= 'A' && str[i] <= 'Z')))
			i++;
		else
		{
			if (str[i] <= 'Z' && str[i] >= 'A')
			{
				str[i] += 32;
			}
			i++;
		}
	}
	return (str);
}
