#include <unistd.h>

void	prog(char *str)
{
	int	i;

	i = 0;
	while (str[i] != '\0')
	{
		write(1, &str[i], 1);
		i++;
	}
	write(1, "\n", 1);
}

int	main(int ac, char **av)
{
	if (ac != 1)
		return (0);
	prog(av[0]);
	return (0);
}
