#include <unistd.h>

void	ft_rev_params(char *str)
{
	int	i;

	i = 0;
	while (str[i] != '\0')
	{
		write(1, &str[i], 1);
		i++;
	}
}

int	main(int ac, char **av)
{
	while (ac != 1)
	{
		ft_rev_params(av[ac - 1]);
		write(1, "\n", 1);
		ac--;
	}
	return (0);
}
